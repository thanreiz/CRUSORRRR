function drumGroove(beats: 3 | 4, count: number): Measure[] {
  if (beats === 3) {
    const ride = parseMeasure(
      3,
      "C2:1:0.85 A3:0.5:0.55 A3:0.5:0.45 A3:1:0.55",
    );
    const crash = parseMeasure(
      3,
      "C#3:1:0.95 A3:0.5:0.55 A3:0.5:0.45 A3:1:0.55",
    );
    const fill = parseMeasure(3, "C2:1:0.9 A2:0.5:0.75 D2:0.5:0.85 C#3:1:0.9");
    return Array.from({ length: count }, (_, i) => {
      if ((i + 1) % 8 === 0) {
        return cloneMeasure(fill);
      }
      if (i % 8 === 0) {
        return cloneMeasure(crash);
      }
      return cloneMeasure(ride);
    });
  }
  const groove = parseMeasure(
    4,
    "C2:0.5:1 F#2:0.5:0.4 D2:0.5:0.9 F#2:0.5:0.35 C2:0.5:0.85 F#2:0.5:0.4 D2:0.5:0.9 F#2:0.5:0.35",
  );
  const crash = parseMeasure(
    4,
    "C#3:0.5:0.95 F#2:0.5:0.4 D2:0.5:0.9 F#2:0.5:0.35 C2:0.5:0.85 F#2:0.5:0.4 D2:0.5:0.9 F#2:0.5:0.35",
  );
  const fill = parseMeasure(
    4,
    "C2:0.5:1 A2:0.5:0.75 A2:0.5:0.8 D2:0.25:0.85 D2:0.25:0.9 A2:0.5:0.8 C#3:0.5:0.95 C2:1:1",
  );
  return Array.from({ length: count }, (_, i) => {
    if ((i + 1) % 8 === 0) {
      return cloneMeasure(fill);
    }
    if (i % 8 === 0) {
      return cloneMeasure(crash);
    }
    return cloneMeasure(groove);
  });
}

function makeSong(
  meta: Omit<Song, "parts" | "bars">,
  partsById: Record<InstrumentId, Measure[]>,
): Song {
  const parts = INSTRUMENT_IDS.map((id) => part(id, partsById[id]));
  assertAlignedParts(parts, BEATS[meta.timeSignature]);
  return { ...meta, bars: parts[0]?.measures.length ?? 0, parts };
}

